#!/usr/bin/env bash
# Generate an RSA-2048 keypair for signed OTA and embed the public half.
#
#   tools/gen_keys.sh          -> private_key.pem (gitignored) + src/public_key.h
#
# Never commit private_key.pem. The public key in src/public_key.h is safe to
# commit: it verifies signatures, it does not create them.
#
# Ed25519 is not used here: ESP-IDF 4.4 ships mbedtls 2.28.7, whose legacy
# mbedtls_pk_verify path has no EdDSA support. RSA + SHA-256 is the pair the
# production firmware actually verifies.
set -euo pipefail

ROOT=$(git rev-parse --show-toplevel 2>/dev/null || pwd)
cd "$ROOT"

KEY=private_key.pem
if [ -e "$KEY" ]; then
    echo "refusing to overwrite existing $KEY" >&2
    exit 1
fi

openssl genpkey -algorithm RSA -pkeyopt rsa_keygen_bits:2048 -out "$KEY"
openssl pkey -in "$KEY" -pubout -outform DER -out /tmp/senpork_public_key.der

{
    echo '#pragma once'
    echo '// Generated by tools/gen_keys.sh. Public key only; the private key is'
    echo '// gitignored and never leaves the signing machine.'
    echo
    xxd -i -n public_key_der /tmp/senpork_public_key.der | sed 's/^unsigned char/const unsigned char/'
} > src/public_key.h

rm -f /tmp/senpork_public_key.der

echo "wrote $KEY (keep it secret) and src/public_key.h"
echo -n "key fingerprint: "
openssl pkey -in "$KEY" -pubout | sha256sum | cut -d' ' -f1
